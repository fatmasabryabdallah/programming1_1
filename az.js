termsGrid.addEventListener(
    "click",
    function (event) {

        if (
            event.target.closest(".favorite-btn")
        ) {
            return;
        }


        const card =
            event.target.closest(".term-card");


        if (!card) {
            return;
        }


        const termName =
            card.querySelector("h3").textContent.trim();


        const term =
            terms.find(function (item) {

                return item.name === termName;

            });


        if (!term) {
            return;
        }


        saveRecentlyViewed(term);

    }
);
