const termsGrid =
    document.getElementById("termsGrid");

const searchInput =
    document.getElementById("searchInput");

const letters =
    document.getElementById("letters");

const noResults =
    document.getElementById("noResults");


let selectedLetter = "all";


/* ==============================
   Display Terms
============================== */

function displayTerms() {

    const searchValue =
        searchInput.value
            .trim()
            .toLowerCase();


    const filteredTerms =
        terms
            .filter(function (term) {

                const matchesLetter =
                    selectedLetter === "all" ||
                    term.name
                        .toUpperCase()
                        .startsWith(selectedLetter);

                const matchesSearch =
                    term.name
                        .toLowerCase()
                        .includes(searchValue) ||

                    term.category
                        .toLowerCase()
                        .includes(searchValue) ||

                    term.description
                        .toLowerCase()
                        .includes(searchValue);

                return matchesLetter && matchesSearch;

            })
            .sort(function (a, b) {

                return a.name.localeCompare(b.name);

            });


    termsGrid.innerHTML = "";


filteredTerms.forEach(function (term) {

    const card = document.createElement(
        term.link ? "a" : "div"
    );

    card.className = "term-card";

    if (term.link) {
        card.href = term.link;
    }


    const firstLetter =
        term.name.charAt(0).toUpperCase();


    const favorites =
        JSON.parse(
            localStorage.getItem("favorites") || "[]"
        );


    const isFavorite =
        favorites.some(function (favorite) {

            return favorite.name === term.name;

        });


    card.innerHTML = `

        <div class="term-top">

            <span class="term-letter">
                ${firstLetter}
            </span>

            <button
                class="favorite-btn ${isFavorite ? "active" : ""}"
                type="button"
                data-name="${term.name}"
            >
                <i class="${isFavorite
                    ? "fa-solid"
                    : "fa-regular"} fa-star"></i>
            </button>

        </div>

        <span class="term-category">
            ${term.category}
        </span>

        <h3>
            ${term.name}
        </h3>

        <p>
            ${term.description}
        </p>

    `;


    termsGrid.appendChild(card);

});



    if (filteredTerms.length === 0) {

        noResults.classList.add("show");

    } else {

        noResults.classList.remove("show");

    }

}

termsGrid.addEventListener(
    "click",
    function (event) {

        const button =
            event.target.closest(".favorite-btn");


        if (!button) {
            return;
        }


        event.preventDefault();


        event.stopPropagation();


        const name =
            button.dataset.name;


        const term =
            terms.find(function (item) {

                return item.name === name;

            });


        if (!term) {
            return;
        }


        let favorites =
            JSON.parse(
                localStorage.getItem("favorites") || "[]"
            );


        const exists =
            favorites.some(function (favorite) {

                return favorite.name === name;

            });


        if (exists) {

            favorites =
                favorites.filter(function (favorite) {

                    return favorite.name !== name;

                });

        } else {

            favorites.push(term);

        }


        localStorage.setItem(
            "favorites",
            JSON.stringify(favorites)
        );


        displayTerms();

    }
);



