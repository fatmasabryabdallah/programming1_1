function saveRecentlyViewed(term) {

    let viewed =
        JSON.parse(
            localStorage.getItem("recentlyViewed") || "[]"
        );


    const alreadyViewed =
        viewed.some(function (item) {

            return item.name === term.name;

        });


    if (!alreadyViewed) {

        viewed.push(term);

    }


    localStorage.setItem(
        "recentlyViewed",
        JSON.stringify(viewed)
    );

}
